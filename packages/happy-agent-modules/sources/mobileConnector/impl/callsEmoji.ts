/** Four emoji from a raw key: Telegram's function over `SHA256(key)`. */
export function callsEmojiForRawKey(key: Uint8Array): readonly string[] {
    const data = createHash("sha256").update(key).digest();
    const result: string[] = [];
    for (let index = 0; index < 4; index += 1) {
        const value = data.readBigUInt64BE(index * 8) & 0x7fff_ffff_ffff_ffffn;
        const emoji = CALLS_EMOJI[Number(value % BigInt(CALLS_EMOJI.length))];
        if (emoji === undefined) throw new Error("The Telegram emoji table is incomplete.");
        result.push(emoji);
    }
    return result;
}

/** The table's checksum, so a test can prove it matches Telegram's. */
export function callsEmojiChecksum(): string {
    return createHash("sha256").update(CALLS_EMOJI.join("\n"), "utf8").digest("hex");
}
